import type { ElementSample, Target } from "../shared/types.js";

// Finding elements by selector and/or visible text, and writing selectors that survive redesigns.

const CLICKABLE =
  "a, button, [role=button], [role=link], [role=menuitem], [role=tab], input[type=submit], input[type=button], summary, label, [onclick], [tabindex]";

export function safeQueryAll(selector: string, root: ParentNode = document): Element[] {
  try {
    return [...root.querySelectorAll(selector)];
  } catch {
    return [];
  }
}

export function isValidSelector(selector: string): boolean {
  try {
    document.createDocumentFragment().querySelector(selector);
    return true;
  } catch {
    return false;
  }
}

const normalise = (text: string | null | undefined): string =>
  (text ?? "").replace(/\s+/g, " ").trim().toLowerCase();

/** Elements for a target: by selector, filtered by text; or the clickable elements whose text matches. */
export function findTargets(target: Target): Element[] {
  const candidates = target.selector
    ? safeQueryAll(target.selector)
    : target.text
      ? safeQueryAll(CLICKABLE)
      : [];
  if (!target.text) return candidates;
  const wanted = normalise(target.text);
  const exact = candidates.filter(
    (el) =>
      normalise((el as HTMLElement).innerText ?? el.textContent) === wanted ||
      normalise(el.getAttribute("aria-label")) === wanted,
  );
  if (exact.length) return exact;
  return candidates.filter((el) =>
    normalise((el as HTMLElement).innerText ?? el.textContent).includes(wanted),
  );
}

/** Class names that look generated by a build (they change on every release). */
export function isGeneratedClass(name: string): boolean {
  return (
    /^(css|sc|jsx|emotion|styled|svelte|astro|chakra|mui|tw)-[\w-]*$/i.test(name) ||
    /^_?[a-zA-Z]{1,3}[0-9][\w-]{3,}$/.test(name) ||
    (/[_-][a-zA-Z0-9]{5,}$/.test(name) && /\d/.test(name)) ||
    (/^[a-z0-9]{6,}$/i.test(name) && /\d/.test(name) && /[a-z]/i.test(name)) ||
    name.length > 40
  );
}

const isStableId = (id: string): boolean =>
  Boolean(id) &&
  !/\d{3,}|^[\da-f-]{16,}$|:|^ember|^react|^radix-|^headlessui-/i.test(id) &&
  id.length < 40;

const STABLE_ATTRIBUTES = [
  "data-testid",
  "data-test-id",
  "data-test",
  "data-qa",
  "data-cy",
  "data-component",
  "aria-label",
  "name",
  "role",
  "itemprop",
  "data-type",
  "type",
];

function attributeSelector(name: string, value: string): string {
  return `[${name}="${CSS.escape(value).replace(/\\ /g, " ")}"]`;
}

function stableClasses(el: Element): string[] {
  return [...el.classList].filter((name) => !isGeneratedClass(name)).slice(0, 3);
}

/** A short description of one element, without position. */
export function descriptor(el: Element): string {
  const tag = el.tagName.toLowerCase();
  if (isStableId(el.id)) return `${tag}#${CSS.escape(el.id)}`;
  for (const name of STABLE_ATTRIBUTES) {
    const value = el.getAttribute(name);
    if (value && value.length < 60 && !(name === "role" && tag !== "div" && tag !== "span"))
      return tag + attributeSelector(name, value);
  }
  const classes = stableClasses(el);
  return tag + classes.map((c) => "." + CSS.escape(c)).join("");
}

const unique = (selector: string, el: Element): boolean => {
  const found = safeQueryAll(selector);
  return found.length === 1 && found[0] === el;
};

function withPosition(el: Element): string {
  const base = descriptor(el);
  const parent = el.parentElement;
  if (!parent) return base;
  const same = [...parent.children].filter((child) => child.tagName === el.tagName);
  return same.length > 1 ? `${base}:nth-of-type(${same.indexOf(el) + 1})` : base;
}

/** Selectors that find exactly this element, best first. */
function byHref(el: Element): string | undefined {
  const href = el.getAttribute("href");
  if (!href || href.length >= 80 || href.startsWith("javascript:")) return undefined;
  const selector = `${el.tagName.toLowerCase()}[href="${CSS.escape(href)}"]`;
  return unique(selector, el) ? selector : undefined;
}

export function selectorsFor(el: Element): string[] {
  const own = descriptor(el);
  const out = [unique(own, el) ? own : undefined, byHref(el)].filter((s): s is string =>
    Boolean(s),
  );
  return [...new Set([...out, ...anchoredSelectors(el, own, 3 - out.length)])].slice(0, 4);
}

/** Walks up to an ancestor that is unique on the page, then back down to the element. */
function anchoredSelectors(el: Element, own: string, wanted: number): string[] {
  const out: string[] = [];
  const chain: string[] = [];
  for (
    let current: Element | null = el;
    current && current !== document.documentElement;
    current = current.parentElement
  ) {
    chain.unshift(current === el ? own : withPosition(current));
    const selector = chain.join(" > ");
    if (unique(descriptor(current), current) || unique(selector, el)) {
      const anchored =
        current === el ? own : `${descriptor(current)} ${chain.slice(1).join(" > ")}`;
      if (unique(anchored, el)) out.push(anchored);
      else if (unique(selector, el)) out.push(selector);
      if (out.length >= Math.max(1, wanted)) break;
    }
  }
  return out;
}

/** A selector for this element and others like it (repeated cards, rows, ads). */
export function similarSelector(el: Element): { selector: string; count: number } | undefined {
  const own = descriptor(el);
  const options = [own];
  const parent = el.parentElement;
  if (parent) options.push(`${descriptor(parent)} > ${own}`);
  const grand = parent?.parentElement;
  if (grand && parent) options.push(`${descriptor(grand)} > ${descriptor(parent)} > ${own}`);
  for (const selector of options) {
    const found = safeQueryAll(selector);
    if (found.length > 1 && found.includes(el) && found.length < 400)
      return { selector, count: found.length };
  }
  return undefined;
}

export function sampleOf(el: Element): ElementSample {
  const attrs: Record<string, string> = {};
  for (const attr of el.attributes)
    if (attr.value.length < 80 && !attr.name.startsWith("on") && attr.name !== "style")
      attrs[attr.name] = attr.value;
  return {
    tag: el.tagName.toLowerCase(),
    text: (el as HTMLElement).innerText?.trim().slice(0, 80) ?? el.textContent?.trim().slice(0, 80),
    attrs,
  };
}
